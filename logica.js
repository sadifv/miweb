// Definición e inicialización de variables
let precio = 25.50;
let cantidad = 3;

// Operación Aritmética (Multiplicación)
let subtotal = precio * cantidad;

// Suma del Impuesto del 15%
let total = subtotal + (subtotal * 0.15);

// Presentación de resultado por pantalla
console.log("El valor del articulo es: " + precio);
console.log("El numero de articulos son: " + cantidad);
console.log("El total a pagar es: " + total);